-- =====================================================================
-- seigura.com 人物中心データベース  01: スキーマ定義
-- 対象: PostgreSQL 15 以上（UNIQUE NULLS NOT DISTINCT を使用）
--
-- 方針
--   * persons.person_id が唯一の人物ID。名鑑・タグ・記事・イベント・
--     掲載号・連載はすべてこの ID を経由して人物に紐付く。
--   * 記事は「人物タグ」で紐付ける。タグ自体が person_id を持つので、
--     編集者がタグを付けるだけで個人ページに記事が載る。
--   * イベント・掲載号・連載は役割（MC・表紙・執筆など）を持つため、
--     person_id を直接参照する中間テーブルで紐付ける。
--   * 既存IDはそのまま主キーに流用できるよう IDENTITY は BY DEFAULT。
--       persons.person_id   = 名鑑ID        （/directory/{id}/）
--       tags.tag_id         = WordPress term_id
--       articles.article_id = WordPress post ID（/news/{id}/ など）
--   * DB のタイムゾーンは Asia/Tokyo を想定（日付比較に使うため）。
-- =====================================================================

SET client_encoding = 'UTF8';

-- ---------------------------------------------------------------------
-- 共通関数
-- ---------------------------------------------------------------------

-- updated_at 自動更新
CREATE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END $$;

-- 名前照合用の正規化（全角半角統一・空白と中黒を除去・小文字化）
--   '森野 くるみ' / '森野　くるみ' / '森野くるみ' → 同一視
CREATE FUNCTION normalize_name(s text) RETURNS text
LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE AS $$
  SELECT lower(regexp_replace(normalize(s, NFKC), '[[:space:]・･]', '', 'g'))
$$;

-- 表示用ラベル（コード値 → 日本語）
CREATE TABLE code_labels (
  domain     text    NOT NULL,
  code       text    NOT NULL,
  label      text    NOT NULL,
  sort_order integer NOT NULL DEFAULT 0,
  PRIMARY KEY (domain, code)
);

-- =====================================================================
-- 1. 人物（名鑑とタグの共通マスタ）
-- =====================================================================

CREATE TABLE persons (
  person_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_type  text   NOT NULL DEFAULT 'individual'
               CHECK (person_type IN ('individual', 'unit')),
  display_name text   NOT NULL,                       -- 例: 春風 ひより
  name_kana    text   NOT NULL                        -- ひらがな（姓名間スペース可）
               CHECK (name_kana ~ '^[ぁ-ゖ][ぁ-ゖー　 ・]*$'),
  name_en      text,
  status       text   NOT NULL DEFAULT 'active'
               CHECK (status IN ('active', 'hiatus', 'retired', 'merged')),
  merged_into  bigint REFERENCES persons (person_id),  -- 重複登録の統合先
  -- 名鑑の五十音索引（あ/か/さ…）
  kana_row     text GENERATED ALWAYS AS (
                 CASE
                   WHEN name_kana ~ '^[ぁ-お]' THEN 'あ'
                   WHEN name_kana ~ '^[か-ご]' THEN 'か'
                   WHEN name_kana ~ '^[さ-ぞ]' THEN 'さ'
                   WHEN name_kana ~ '^[た-ど]' THEN 'た'
                   WHEN name_kana ~ '^[な-の]' THEN 'な'
                   WHEN name_kana ~ '^[は-ぽ]' THEN 'は'
                   WHEN name_kana ~ '^[ま-も]' THEN 'ま'
                   WHEN name_kana ~ '^[ゃ-よ]' THEN 'や'
                   WHEN name_kana ~ '^[ら-ろ]' THEN 'ら'
                   ELSE 'わ'
                 END) STORED,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  UNIQUE (person_id, person_type),                    -- unit_members の型チェック用
  CHECK ((status = 'merged') = (merged_into IS NOT NULL)),
  CHECK (merged_into <> person_id)
);
CREATE INDEX persons_kana_idx      ON persons (kana_row, name_kana) WHERE status <> 'merged';
CREATE INDEX persons_name_norm_idx ON persons (normalize_name(display_name));
CREATE TRIGGER persons_updated_at BEFORE UPDATE ON persons
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 旧芸名・別名・別表記（検索とタグ紐付け候補の抽出に使う）
CREATE TABLE person_names (
  person_name_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  person_id      bigint NOT NULL REFERENCES persons ON DELETE CASCADE,
  name           text   NOT NULL,
  name_kana      text,
  name_kind      text   NOT NULL CHECK (name_kind IN ('former', 'alias', 'alt_spelling')),
  used_from      date,
  used_until     date,
  UNIQUE (person_id, name)
);
CREATE INDEX person_names_name_norm_idx ON person_names (normalize_name(name));

-- ユニット・グループの在籍履歴（person_type で unit / individual を強制）
CREATE TABLE unit_members (
  unit_member_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  unit_id        bigint NOT NULL,
  unit_type      text   NOT NULL DEFAULT 'unit'       CHECK (unit_type = 'unit'),
  member_id      bigint NOT NULL,
  member_type    text   NOT NULL DEFAULT 'individual' CHECK (member_type = 'individual'),
  joined_on      date,
  left_on        date,                                -- 在籍最終日（NULL = 在籍中）
  FOREIGN KEY (unit_id, unit_type)     REFERENCES persons (person_id, person_type) ON DELETE CASCADE,
  FOREIGN KEY (member_id, member_type) REFERENCES persons (person_id, person_type) ON DELETE CASCADE,
  UNIQUE NULLS NOT DISTINCT (unit_id, member_id, joined_on),
  CHECK (left_on IS NULL OR joined_on IS NULL OR joined_on <= left_on)
);
CREATE INDEX unit_members_member_idx ON unit_members (member_id);

-- =====================================================================
-- 2. 名鑑（プロフィール・所属・出演作品）
-- =====================================================================

CREATE TABLE person_profiles (
  person_id    bigint PRIMARY KEY REFERENCES persons ON DELETE CASCADE,
  birth_year   smallint CHECK (birth_year BETWEEN 1900 AND 2100),  -- 非公表なら NULL
  birth_month  smallint CHECK (birth_month BETWEEN 1 AND 12),
  birth_day    smallint CHECK (birth_day BETWEEN 1 AND 31),
  birthplace   text,                                  -- 出身地
  blood_type   text CHECK (blood_type IN ('A', 'B', 'O', 'AB')),
  hobbies      text,                                  -- 趣味・特技・資格
  biography    text,
  image_url    text,
  is_published boolean NOT NULL DEFAULT false,
  updated_at   timestamptz NOT NULL DEFAULT now(),
  CHECK (birth_day IS NULL OR birth_month IS NOT NULL)
);
CREATE INDEX person_profiles_birthday_idx ON person_profiles (birth_month, birth_day) WHERE is_published;
CREATE TRIGGER person_profiles_updated_at BEFORE UPDATE ON person_profiles
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE agencies (
  agency_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name      text NOT NULL UNIQUE,
  name_kana text,
  url       text
);

-- 所属履歴（ended_on IS NULL が現所属。1人1件まで）
CREATE TABLE person_affiliations (
  affiliation_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  person_id      bigint NOT NULL REFERENCES persons ON DELETE CASCADE,
  agency_id      bigint NOT NULL REFERENCES agencies,
  started_on     date,
  ended_on       date,
  UNIQUE NULLS NOT DISTINCT (person_id, agency_id, started_on),
  CHECK (ended_on IS NULL OR started_on IS NULL OR started_on <= ended_on)
);
CREATE UNIQUE INDEX person_affiliations_current_idx ON person_affiliations (person_id) WHERE ended_on IS NULL;

CREATE TABLE works (
  work_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       text NOT NULL,
  title_kana  text,
  work_type   text NOT NULL DEFAULT 'anime'
              CHECK (work_type IN ('anime', 'game', 'dub', 'film', 'drama_cd', 'radio', 'stage', 'other')),
  released_on date
);
CREATE INDEX works_title_norm_idx ON works (normalize_name(title), work_type);

-- 出演作品（名鑑の「出演作品」欄）
CREATE TABLE castings (
  casting_id     bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  person_id      bigint  NOT NULL REFERENCES persons ON DELETE CASCADE,
  work_id        bigint  NOT NULL REFERENCES works ON DELETE CASCADE,
  character_name text,
  is_main        boolean NOT NULL DEFAULT false,      -- 代表作として上位表示
  sort_order     integer NOT NULL DEFAULT 0,
  UNIQUE NULLS NOT DISTINCT (person_id, work_id, character_name)
);
CREATE INDEX castings_work_idx ON castings (work_id);

-- =====================================================================
-- 3. タグ（人物タグは person_id を持つ = 名鑑と同じID）
-- =====================================================================

CREATE TABLE tags (
  tag_id     bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug       text    NOT NULL UNIQUE,                 -- /tag/{slug}/（WordPress と同じ形式で保存）
  name       text    NOT NULL,
  tag_type   text    NOT NULL DEFAULT 'topic' CHECK (tag_type IN ('person', 'work', 'topic')),
  person_id  bigint  REFERENCES persons ON DELETE RESTRICT,
  work_id    bigint  REFERENCES works   ON DELETE RESTRICT,
  is_primary boolean NOT NULL DEFAULT false,          -- 代表タグ。旧芸名・表記ゆれタグは false
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((tag_type = 'person') = (person_id IS NOT NULL)),
  CHECK ((tag_type = 'work')   = (work_id   IS NOT NULL)),
  CHECK (NOT is_primary OR tag_type <> 'topic')
);
CREATE UNIQUE INDEX tags_primary_person_idx ON tags (person_id) WHERE is_primary AND person_id IS NOT NULL;
CREATE UNIQUE INDEX tags_primary_work_idx   ON tags (work_id)   WHERE is_primary AND work_id   IS NOT NULL;
CREATE INDEX tags_person_idx    ON tags (person_id) WHERE person_id IS NOT NULL;
CREATE INDEX tags_name_norm_idx ON tags (normalize_name(name));

-- =====================================================================
-- 4. 連載
-- =====================================================================

CREATE TABLE serials (
  serial_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       text NOT NULL,
  slug        text UNIQUE,
  medium      text NOT NULL CHECK (medium IN ('web', 'magazine', 'both')),
  description text,
  started_on  date,
  ended_on    date,                                   -- NULL = 連載中
  CHECK (ended_on IS NULL OR started_on IS NULL OR started_on <= ended_on)
);

-- レギュラー（執筆者・パーソナリティ等）。ゲストは記事タグ／誌面掲載から自動判定
CREATE TABLE serial_members (
  serial_id  bigint  NOT NULL REFERENCES serials ON DELETE CASCADE,
  person_id  bigint  NOT NULL REFERENCES persons ON DELETE CASCADE,
  role       text    NOT NULL DEFAULT 'author'
             CHECK (role IN ('author', 'host', 'regular', 'illustrator')),
  sort_order integer NOT NULL DEFAULT 0,
  PRIMARY KEY (serial_id, person_id, role)
);
CREATE INDEX serial_members_person_idx ON serial_members (person_id);

-- =====================================================================
-- 5. 記事
-- =====================================================================

CREATE TABLE articles (
  article_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  article_type  text   NOT NULL
                CHECK (article_type IN ('news', 'interview', 'column', 'event', 'magazine', 'school', 'other')),
  path          text   NOT NULL UNIQUE,               -- 例: /news/176875/
  title         text   NOT NULL,
  excerpt       text,
  thumbnail_url text,
  serial_id     bigint REFERENCES serials,            -- 連載の回なら連載ID
  episode_no    integer CHECK (episode_no > 0),
  status        text   NOT NULL DEFAULT 'draft'
                CHECK (status IN ('draft', 'scheduled', 'published', 'private')),
  published_at  timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  CHECK (status NOT IN ('scheduled', 'published') OR published_at IS NOT NULL),
  CHECK (episode_no IS NULL OR serial_id IS NOT NULL),
  UNIQUE (serial_id, episode_no)
);
CREATE INDEX articles_published_idx ON articles (published_at DESC) WHERE status IN ('published', 'scheduled');
CREATE INDEX articles_serial_idx    ON articles (serial_id, published_at DESC) WHERE serial_id IS NOT NULL;
CREATE TRIGGER articles_updated_at BEFORE UPDATE ON articles
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE article_tags (
  article_id bigint NOT NULL REFERENCES articles ON DELETE CASCADE,
  tag_id     bigint NOT NULL REFERENCES tags     ON DELETE CASCADE,
  PRIMARY KEY (article_id, tag_id)
);
CREATE INDEX article_tags_tag_idx ON article_tags (tag_id, article_id);

-- =====================================================================
-- 6. イベント・番組出演
-- =====================================================================

CREATE TABLE events (
  event_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title        text NOT NULL,
  event_type   text NOT NULL DEFAULT 'event'
               CHECK (event_type IN ('live', 'event', 'release_event', 'stage', 'screening', 'broadcast', 'stream', 'other')),
  starts_at    timestamptz NOT NULL,
  ends_at      timestamptz,
  venue        text,
  official_url text,
  status       text NOT NULL DEFAULT 'scheduled'
               CHECK (status IN ('scheduled', 'postponed', 'cancelled')),
  is_published boolean NOT NULL DEFAULT true,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  CHECK (ends_at IS NULL OR starts_at <= ends_at)
);
CREATE INDEX events_starts_idx ON events (starts_at);
CREATE TRIGGER events_updated_at BEFORE UPDATE ON events
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 出演者（ユニットを登録するとメンバーにも在籍期間内なら表示される）
CREATE TABLE event_performers (
  event_id   bigint  NOT NULL REFERENCES events  ON DELETE CASCADE,
  person_id  bigint  NOT NULL REFERENCES persons ON DELETE CASCADE,
  role       text    NOT NULL DEFAULT 'performer' CHECK (role IN ('performer', 'mc', 'guest', 'host')),
  appearance text    NOT NULL DEFAULT 'confirmed' CHECK (appearance IN ('confirmed', 'cancelled')),
  sort_order integer NOT NULL DEFAULT 0,
  PRIMARY KEY (event_id, person_id)
);
CREATE INDEX event_performers_person_idx ON event_performers (person_id);

-- イベントと告知・レポート記事
CREATE TABLE event_articles (
  event_id   bigint NOT NULL REFERENCES events   ON DELETE CASCADE,
  article_id bigint NOT NULL REFERENCES articles ON DELETE CASCADE,
  relation   text   NOT NULL DEFAULT 'announcement' CHECK (relation IN ('announcement', 'report')),
  PRIMARY KEY (event_id, article_id)
);
CREATE INDEX event_articles_article_idx ON event_articles (article_id);

-- =====================================================================
-- 7. 雑誌（声優グランプリ 各号）
-- =====================================================================

CREATE TABLE magazine_issues (
  issue_id        bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  publication     text    NOT NULL DEFAULT '声優グランプリ',
  issue_label     text    NOT NULL,                   -- 例: 2026年12月号
  cover_month     date,                               -- 号表記の年月（月初日）。増刊等は NULL 可
  release_date    date    NOT NULL,                   -- 発売日
  path            text    UNIQUE,                     -- 例: /magazine_books/176667/
  cover_image_url text,
  price_yen       integer CHECK (price_yen >= 0),
  is_published    boolean NOT NULL DEFAULT true,
  UNIQUE (publication, issue_label)
);
CREATE INDEX magazine_issues_release_idx ON magazine_issues (release_date DESC);

-- 号の中の企画（表紙・巻頭特集・グラビア・連載ページ…）
CREATE TABLE issue_items (
  issue_item_id bigint   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  issue_id      bigint   NOT NULL REFERENCES magazine_issues ON DELETE CASCADE,
  item_type     text     NOT NULL
                CHECK (item_type IN ('cover', 'main_feature', 'feature', 'gravure', 'interview', 'serial', 'appendix',
                                     'appearance', 'other')),             -- appearance = 掲載（企画の種類が不明）
  title         text,
  page_from     smallint,
  page_to       smallint,
  serial_id     bigint   REFERENCES serials,          -- item_type = 'serial' のとき必須
  sort_order    integer  NOT NULL DEFAULT 0,
  CHECK (page_to IS NULL OR page_from IS NULL OR page_from <= page_to),
  CHECK ((item_type = 'serial') = (serial_id IS NOT NULL))
);
CREATE INDEX issue_items_issue_idx  ON issue_items (issue_id);
CREATE INDEX issue_items_serial_idx ON issue_items (serial_id) WHERE serial_id IS NOT NULL;

CREATE TABLE issue_item_persons (
  issue_item_id bigint  NOT NULL REFERENCES issue_items ON DELETE CASCADE,
  person_id     bigint  NOT NULL REFERENCES persons     ON DELETE CASCADE,
  sort_order    integer NOT NULL DEFAULT 0,
  PRIMARY KEY (issue_item_id, person_id)
);
CREATE INDEX issue_item_persons_person_idx ON issue_item_persons (person_id);

